// Local CDP smoke check against an isolated headless Chrome on port 9437.
// External image requests are deliberately blocked to exercise the fallback.
import {writeFileSync,readFileSync} from 'node:fs'
const catalog=JSON.parse(readFileSync('src/generated/catalog.json','utf8'))
const targets=await (await fetch('http://127.0.0.1:9437/json/list')).json()
const ws=new WebSocket(targets.find(t=>t.type==='page').webSocketDebuggerUrl)
await new Promise(resolve=>ws.addEventListener('open',resolve,{once:true}))
let seq=0;const pending=new Map()
ws.addEventListener('message',event=>{const msg=JSON.parse(event.data);if(msg.id){const pair=pending.get(msg.id);pending.delete(msg.id);if(msg.error)pair.reject(new Error(JSON.stringify(msg.error)));else pair.resolve(msg.result)}})
function send(method,params={}){return new Promise((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}))})}
const errors=[]
ws.addEventListener('message',event=>{const msg=JSON.parse(event.data);if(msg.method==='Runtime.exceptionThrown')errors.push(msg.params.exceptionDetails.text)})
await send('Runtime.enable');await send('Page.enable');await send('Network.enable')
// Local UI checks do not need third-party image requests.
await send('Network.setBlockedURLs',{urls:['*://raw.githubusercontent.com/*','*://github.com/*','*://img.youtube.com/*','*://user-images.githubusercontent.com/*']})
const delay=ms=>new Promise(r=>setTimeout(r,ms))
async function evaluate(expression){const r=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value}
function check(value,message){if(!value)throw Error(message)}
async function go(path){await send('Page.navigate',{url:'http://localhost:4317'+path});await delay(900)}
await send('Emulation.setDeviceMetricsOverride',{width:1280,height:900,deviceScaleFactor:1,mobile:false})
await go('/')
check(await evaluate("location.pathname==='/' && location.search===''"),'Default URL changed')
check(await evaluate("getComputedStyle(document.querySelector('.sidebar-content')).display!=='none'"),'Desktop sidebar hidden')
check(await evaluate("[...document.querySelectorAll('.cover img')].filter(i=>i.getBoundingClientRect().top<innerHeight && i.complete && i.naturalWidth===0).length===0"),'Broken image did not fall back')
const initial=await evaluate("document.querySelectorAll('.project-card').length")
check(initial===catalog.projects.length,'Rendered project count differs from generated catalog')
const mostStarred=[...catalog.projects].sort((a,b)=>(b.metrics?.stars ?? -1)-(a.metrics?.stars ?? -1)||a.name.localeCompare(b.name))[0].name
check(await evaluate("document.querySelector('.project-card h2').textContent")===mostStarred,'Default Star sort is incorrect')
await evaluate("document.querySelector('.device-sidebar button.selected').click()")
await delay(200)
await evaluate("[...document.querySelectorAll('.tags button')].find(b=>b.textContent==='AI').click()")
await delay(300)
const filtered=await evaluate("document.querySelectorAll('.project-card').length")
check(filtered>0&&filtered<initial,'Hydrated tag filter failed')
check(await evaluate("location.search.includes('tag=ai') && !location.search.includes('sort=')"),'Search URL not clean')
await evaluate("document.querySelector('.language').value='ja'; document.querySelector('.language').dispatchEvent(new Event('change',{bubbles:true}))")
await delay(900)
check(await evaluate("location.pathname==='/ja' && location.search.includes('tag=ai') && document.documentElement.lang==='ja'"),'Language switch lost route or filter')
await go('/devices?maker=m5stack')
check(await evaluate("!document.querySelector('.device-sidebar')"),'Sidebar on devices')
check(await evaluate("document.querySelector('select').value==='en'"),'Locale state')
await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true})
await go('/zh')
check(await evaluate("document.documentElement.scrollWidth<=390"),'Mobile horizontal overflow')
check(await evaluate("getComputedStyle(document.querySelector('.sidebar-content')).display==='none'"),'Mobile sidebar not collapsed')
await evaluate("document.querySelector('.mobile-device-toggle').click()")
await delay(150)
check(await evaluate("getComputedStyle(document.querySelector('.sidebar-content')).display!=='none'"),'Mobile chooser did not open')
await evaluate("document.querySelector('.mobile-device-toggle').click()")
await delay(150)
await evaluate("document.querySelector('.mobile-device-toggle').click()")
await delay(150)
await evaluate(`const input=document.querySelector('.device-sidebar input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'M5CardputerADV'); input.dispatchEvent(new Event('input',{bubbles:true}))`)
await delay(200)
check(await evaluate("[...document.querySelectorAll('.sidebar-content details button')].every(b=>b.textContent.includes('Cardputer'))"),'Device search did not narrow model options')
await evaluate("[...document.querySelectorAll('.sidebar-content details button')].find(b=>b.textContent.startsWith('Cardputer ADV')).click()")
await delay(300)
check(await evaluate("location.search.includes('device=m5stack-cardputer-adv')"),'Model selection did not update URL')
check(await evaluate("getComputedStyle(document.querySelector('.sidebar-content')).display==='none'"),'Model choice did not collapse mobile selector')
const expectedForAdv=catalog.projects.filter(p=>p.devices.some(d=>d.deviceId==='m5stack-cardputer-adv')).length
check(await evaluate("document.querySelectorAll('.project-card').length")===expectedForAdv,'Model selection shows unrelated projects')
await go('/ja/devices')
check(await evaluate("document.querySelectorAll('.project-card').length")===catalog.devices.length,'Device catalog count differs from generated data')
check(await evaluate("document.documentElement.scrollWidth<=390"),'Mobile device directory overflow')
await evaluate("const maker=document.querySelector('.device-toolbar select'); maker.value='adafruit'; maker.dispatchEvent(new Event('change',{bubbles:true}))")
await delay(250)
check(await evaluate("document.querySelectorAll('.project-card').length")===catalog.devices.filter(d=>d.manufacturer.id==='adafruit').length,'Hydrated manufacturer filter failed')
await evaluate("document.querySelector('a[href=\"/ja/devices/adafruit-feather-esp32s2\"]').click()")
await delay(350)
check(await evaluate("location.pathname==='/ja/devices/adafruit-feather-esp32s2' && !document.querySelector('.device-sidebar')"),'Device detail navigation failed')
check(await evaluate("document.querySelectorAll('.project-card').length")===catalog.projects.filter(p=>p.devices.some(d=>d.deviceId==='adafruit-feather-esp32s2')).length,'New device relation is missing from detail page')
await go('/zh')
const mobile=await send('Page.captureScreenshot',{format:'png'});writeFileSync('/tmp/esp32-mobile.png',Buffer.from(mobile.data,'base64'))
await send('Emulation.setDeviceMetricsOverride',{width:1280,height:900,deviceScaleFactor:1,mobile:false})
await go('/')
const desktop=await send('Page.captureScreenshot',{format:'png'});writeFileSync('/tmp/esp32-desktop.png',Buffer.from(desktop.data,'base64'))
check(errors.length===0,'Browser errors: '+errors.join(', '))
console.log(JSON.stringify({passed:true,initialProjects:initial,aiFiltered:filtered,errors,screenshots:['/tmp/esp32-mobile.png','/tmp/esp32-desktop.png']}))
ws.close()
